import { readFileSync } from "node:fs";
import { join } from "node:path";

/** Where the SDK's authorization imports the client ID rule that the hosted deploy check uses. */
export const oauthClientIdRulePath = "packages/sdk/src/implementation/oauth-client-id.ts";

export function oauthClientIdRuleSource(root: string) {
  return `// Generated by Basalt's upstream preparation from scripts/oauth-client-id.ts.\n${readFileSync(join(root, "scripts/oauth-client-id.ts"), "utf8")}`;
}
