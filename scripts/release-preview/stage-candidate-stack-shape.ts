/**
 * The shape of a candidate's `alchemy.run.ts`, read from its syntax tree and never evaluated: the
 * heal overlay's rehearsal-stage handling, and nothing that could stand in for it. Comments, dead
 * code and a second stack are not handling. One cohesive rule set over one file's syntax, so it
 * stays one module.
 */
import { existsSync, lstatSync, readFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";
import ts from "../architecture/typescript.ts";

/** Logical ids only production declares; a rehearsal stage that declared one would adopt it. */
export const productionOnlyIds = new Set([
  "PublicSite",
  "ApiBrowserCheckExemption",
  "AuthEmailDomain",
  "PublicSiteWaitlist",
]);
const namers = new Set(["disposableStageNames", "subjectFromStage"]);

/** A name the stack file imports: its exported name there, and the module it comes from. */
export type Imported = { readonly exported: string; readonly from: string };

export type StackShape =
  | { readonly plain: string }
  | { readonly stack: Imported; readonly namer: Imported };

const parse = (path: string, text: string) =>
  ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
// `parseDiagnostics` is the parser's own list; absent, the file counts as not parsed.
const parsed = (file: ts.SourceFile) =>
  (file as unknown as { parseDiagnostics?: readonly unknown[] }).parseDiagnostics?.length === 0;

function each(node: ts.Node, visit: (node: ts.Node) => void) {
  visit(node);
  ts.forEachChild(node, (child) => each(child, visit));
}

/** Whether `id` is the name a declaration binds, not a reference. */
function declares(id: ts.Identifier) {
  const parent = id.parent as (ts.Node & { name?: ts.Node }) | undefined;
  return (
    parent !== undefined &&
    parent.name === id &&
    (ts.isVariableDeclaration(parent) ||
      ts.isBindingElement(parent) ||
      ts.isParameter(parent) ||
      ts.isFunctionDeclaration(parent) ||
      ts.isFunctionExpression(parent) ||
      ts.isClassDeclaration(parent) ||
      ts.isClassExpression(parent) ||
      ts.isImportSpecifier(parent) ||
      ts.isNamespaceImport(parent) ||
      ts.isImportClause(parent) ||
      ts.isImportEqualsDeclaration(parent) ||
      ts.isEnumDeclaration(parent) ||
      ts.isModuleDeclaration(parent))
  );
}

/** A reference to a binding: not a declaration, a property's own name or an import's original. */
function references(id: ts.Identifier) {
  const parent = id.parent as ts.Node & { name?: ts.Node; propertyName?: ts.Node };
  if (declares(id)) return false;
  if (
    (ts.isPropertyAccessExpression(parent) ||
      ts.isPropertyAssignment(parent) ||
      ts.isMethodDeclaration(parent) ||
      ts.isPropertySignature(parent)) &&
    parent.name === id
  )
    return false;
  return !(
    (ts.isImportSpecifier(parent) || ts.isExportSpecifier(parent)) &&
    parent.propertyName === id
  );
}

const relativeModule = (from: string) => from.startsWith("./") || from.startsWith("../");

/** A relative specifier's file, with TypeScript's `.js`-for-`.ts` spelling, if the tree has it. */
function moduleFile(path: string) {
  for (const candidate of [path, path.replace(/\.js$/u, ".ts"), path.replace(/\.mjs$/u, ".mts")])
    if (existsSync(candidate) && lstatSync(candidate).isFile()) return candidate;
  return undefined;
}

/**
 * Whether a module the stack file imports, or one it re-exports from, writes a production-only id
 * as a string, as Alchemy ids are written (`provisionPublicSiteWaitlist` declares its database
 * there). Modules it only imports are not followed: upstream's cloud deployment declares its own
 * gated resources several imports down, which the stack file cannot gate. A module outside the
 * tree counts as declaring one. A module not there yet (generated by a later build) is skipped:
 * the candidate's prepare has run by now, and this is a backstop against a stack file that forgot
 * its gate, not a sandbox for a candidate that runs with the stage's secrets after it.
 */
function declaresProductionId(tree: string, path: string, seen = new Set<string>()): boolean {
  const inner = relative(tree, path);
  if (inner === "" || inner.startsWith("..") || isAbsolute(inner)) return true;
  const file = moduleFile(path);
  if (!file || seen.has(file)) return false;
  seen.add(file);
  let found = false;
  const reexported: string[] = [];
  each(parse(file, readFileSync(file, "utf8")), (node) => {
    if (ts.isStringLiteralLike(node) && productionOnlyIds.has(node.text)) found = true;
    if (
      ts.isExportDeclaration(node) &&
      node.moduleSpecifier &&
      ts.isStringLiteralLike(node.moduleSpecifier) &&
      relativeModule(node.moduleSpecifier.text)
    )
      reexported.push(resolve(dirname(file), node.moduleSpecifier.text));
  });
  return found || reexported.some((module) => declaresProductionId(tree, module, seen));
}

const bare = (node: ts.Expression) => {
  while (ts.isParenthesizedExpression(node)) node = node.expression;
  return node;
};
const isName = (node: ts.Node, name: string) => ts.isIdentifier(node) && node.text === name;

/** `name === undefined`, either way round. */
function isUndefined(node: ts.Expression, name: string) {
  const test = bare(node);
  return (
    ts.isBinaryExpression(test) &&
    (test.operatorToken.kind === ts.SyntaxKind.EqualsEqualsEqualsToken ||
      test.operatorToken.kind === ts.SyntaxKind.EqualsEqualsToken) &&
    ((isName(test.left, name) && isName(test.right, "undefined")) ||
      (isName(test.left, "undefined") && isName(test.right, name)))
  );
}

/** That test, or a conjunction that requires it. */
function undefinedTest(node: ts.Expression, name: string): boolean {
  const test = bare(node);
  if (
    ts.isBinaryExpression(test) &&
    test.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandToken
  )
    return undefinedTest(test.left, name) || undefinedTest(test.right, name);
  return isUndefined(test, name);
}

/** `process.env.ALCHEMY_STAGE`, read plainly. */
const envStage = (node: ts.Node) =>
  ts.isPropertyAccessExpression(node) &&
  !node.questionDotToken &&
  node.name.text === "ALCHEMY_STAGE" &&
  ts.isPropertyAccessExpression(node.expression) &&
  !node.expression.questionDotToken &&
  node.expression.name.text === "env" &&
  isName(node.expression.expression, "process");

/** The stack file's named imports, by local name. Type-only imports bind nothing at runtime. */
function importsOf(file: ts.SourceFile) {
  const imports = new Map<string, Imported>();
  for (const statement of file.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier))
      continue;
    const clause = statement.importClause;
    if (!clause || clause.isTypeOnly) continue;
    const from = statement.moduleSpecifier.text;
    if (clause.name) imports.set(clause.name.text, { exported: "default", from });
    const bindings = clause.namedBindings;
    if (bindings && ts.isNamespaceImport(bindings))
      imports.set(bindings.name.text, { exported: "*", from });
    if (bindings && ts.isNamedImports(bindings))
      for (const element of bindings.elements)
        if (!element.isTypeOnly)
          imports.set(element.name.text, {
            exported: (element.propertyName ?? element.name).text,
            from,
          });
  }
  return imports;
}

/**
 * The stack file's rehearsal-stage handling, or why it has none (a string). It must have exactly:
 * - one `Stack`, as `export default Alchemy.Stack(stackNameForStage(process.env.ALCHEMY_STAGE), …,
 *   Effect.gen(function* () { … }))`, with `alchemy` imported once, as that namespace, used only
 *   there, and stackNameForStage imported from a relative module (a plain name is returned as such);
 * - in that generator's own body, before anything returns: `const stage = yield* Stage`, then
 *   `const names = disposableStageNames(stage)` (or `subjectFromStage`), then
 *   `const preview = names === undefined ? undefined : …`, and a `preview === undefined` test;
 * - every production-only logical id, and every use of an imported module that declares one, only
 *   where a `preview === undefined` test holds.
 * `process`, `undefined` and those names are never rebound, ALCHEMY_STAGE is only read as the
 * stack's name or named as a key of an `env` it hands on, and no module is loaded at runtime.
 */
export function stackShape(tree: string, text: string): StackShape | string {
  const file = parse("alchemy.run.ts", text);
  if (!parsed(file)) return "its stack file does not parse";
  const imports = importsOf(file);
  const bound = new Map<string, number>();
  const used = new Map<string, number>();
  let stacks = 0;
  let loads = false;
  const stageNames: ts.Node[] = [];
  each(file, (node) => {
    if (ts.isIdentifier(node) && declares(node))
      bound.set(node.text, (bound.get(node.text) ?? 0) + 1);
    if (ts.isIdentifier(node) && references(node))
      used.set(node.text, (used.get(node.text) ?? 0) + 1);
    if ((ts.isIdentifier(node) || ts.isStringLiteralLike(node)) && node.text === "Stack")
      stacks += 1;
    if ((ts.isIdentifier(node) || ts.isStringLiteralLike(node)) && node.text === "ALCHEMY_STAGE")
      stageNames.push(node);
    if (
      ts.isCallExpression(node) &&
      (node.expression.kind === ts.SyntaxKind.ImportKeyword || isName(node.expression, "require"))
    )
      loads = true;
    if (ts.isImportEqualsDeclaration(node)) loads = true;
  });
  const once = (name: string) => bound.get(name) === 1;
  const imported = (
    node: ts.Node,
    exported: (name: string) => boolean,
    from: (path: string) => boolean,
  ) => {
    if (!ts.isIdentifier(node) || !once(node.text)) return undefined;
    const found = imports.get(node.text);
    return found && exported(found.exported) && from(found.from) ? found : undefined;
  };
  if (bound.has("process") || bound.has("undefined")) return "it rebinds process or undefined";
  if (loads) return "it loads a module at runtime";
  if (stacks !== 1) return "its stack file names Stack other than once";
  const alchemy = [...imports].filter(([, { from }]) => from === "alchemy");
  if (alchemy.length !== 1 || alchemy[0]![1].exported !== "*" || used.get(alchemy[0]![0]) !== 1)
    return "it imports alchemy other than as one namespace used only for its Stack";

  const defaults = file.statements.filter(
    (statement) =>
      (ts.isExportAssignment(statement) && !statement.isExportEquals) ||
      (ts.canHaveModifiers(statement) &&
        ts.getModifiers(statement)?.some((m) => m.kind === ts.SyntaxKind.DefaultKeyword)) ||
      (ts.isExportDeclaration(statement) &&
        statement.exportClause !== undefined &&
        ts.isNamedExports(statement.exportClause) &&
        statement.exportClause.elements.some((element) => element.name.text === "default")),
  );
  const exported = defaults.length === 1 ? defaults[0] : undefined;
  const call = exported && ts.isExportAssignment(exported) ? exported.expression : undefined;
  if (
    !call ||
    !ts.isCallExpression(call) ||
    call.arguments.length !== 3 ||
    !ts.isPropertyAccessExpression(call.expression) ||
    call.expression.name.text !== "Stack" ||
    !imported(
      call.expression.expression,
      (name) => name === "*",
      (from) => from === "alchemy",
    )
  )
    return "its default export is not Alchemy.Stack(name, options, program)";

  const [named, , program] = call.arguments as unknown as [
    ts.Expression,
    ts.Expression,
    ts.Expression,
  ];
  if (ts.isStringLiteralLike(named)) return { plain: named.text };
  const stackCall = (node: ts.Node) =>
    ts.isCallExpression(node) &&
    node.arguments.length === 1 &&
    envStage(node.arguments[0]!) &&
    imported(node.expression, (name) => name === "stackNameForStage", relativeModule);
  if (!stackCall(named))
    return "its stack is not named stackNameForStage(process.env.ALCHEMY_STAGE)";
  const stack = imports.get(((named as ts.CallExpression).expression as ts.Identifier).text)!;
  for (const node of stageNames) {
    const read = envStage(node.parent) && stackCall(node.parent.parent);
    // A key of the env a command is handed: `env: { ALCHEMY_STAGE: stage }`.
    const key =
      ts.isPropertyAssignment(node.parent) &&
      node.parent.name === node &&
      ts.isObjectLiteralExpression(node.parent.parent) &&
      ts.isPropertyAssignment(node.parent.parent.parent) &&
      isName(node.parent.parent.parent.name, "env");
    if (!read && !key) return "it touches ALCHEMY_STAGE other than to name its stack";
  }

  let gen: ts.Node = program;
  while (
    ts.isCallExpression(gen) &&
    ts.isPropertyAccessExpression(gen.expression) &&
    gen.expression.name.text === "pipe"
  )
    gen = gen.expression.expression;
  const fn =
    ts.isCallExpression(gen) &&
    ts.isPropertyAccessExpression(gen.expression) &&
    gen.expression.name.text === "gen" &&
    imported(
      gen.expression.expression,
      (name) => name === "Effect",
      (from) => from === "effect",
    ) &&
    gen.arguments.length === 1
      ? gen.arguments[0]
      : undefined;
  if (!fn || !ts.isFunctionExpression(fn) || !fn.asteriskToken)
    return "its stack's program is not one Effect.gen generator";

  const constant = (statement: ts.Statement) => {
    if (!ts.isVariableStatement(statement)) return undefined;
    const list = statement.declarationList;
    const [declaration] = list.declarations;
    return (list.flags & ts.NodeFlags.Const) !== 0 &&
      list.declarations.length === 1 &&
      ts.isIdentifier(declaration!.name) &&
      once(declaration!.name.text) &&
      declaration!.initializer
      ? { name: declaration!.name.text, value: declaration!.initializer }
      : undefined;
  };
  let stage: string | undefined;
  let names: string | undefined;
  let namer: Imported | undefined;
  let preview: string | undefined;
  for (const statement of fn.body.statements) {
    if (ts.isReturnStatement(statement) || ts.isThrowStatement(statement))
      return "its program returns before its preview decision";
    const declared = constant(statement);
    if (!declared) continue;
    const { name, value } = declared;
    if (stage === undefined) {
      if (
        ts.isYieldExpression(value) &&
        value.asteriskToken &&
        value.expression &&
        imported(
          value.expression,
          (e) => e === "Stage",
          (from) => from === "alchemy/Stage",
        )
      )
        stage = name;
    } else if (names === undefined) {
      if (
        ts.isCallExpression(value) &&
        value.arguments.length === 1 &&
        isName(value.arguments[0]!, stage)
      ) {
        namer = imported(value.expression, (e) => namers.has(e), relativeModule);
        if (namer) names = name;
      }
    } else if (
      ts.isConditionalExpression(value) &&
      isUndefined(value.condition, names) &&
      isName(bare(value.whenTrue), "undefined")
    ) {
      preview = name;
      break;
    }
  }
  if (!preview || !namer) return "no preview decision of its own tree's preview names";
  const previewName = preview;

  // Where a node runs only when `preview === undefined` holds, inside the generator.
  const production = (node: ts.Node) => {
    for (let child = node, parent = node.parent; parent; child = parent, parent = parent.parent) {
      if (parent === fn) return false;
      if (
        (ts.isIfStatement(parent) &&
          parent.thenStatement === child &&
          undefinedTest(parent.expression, previewName)) ||
        (ts.isConditionalExpression(parent) &&
          parent.whenTrue === child &&
          undefinedTest(parent.condition, previewName)) ||
        (ts.isBinaryExpression(parent) &&
          parent.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandToken &&
          parent.right === child &&
          undefinedTest(parent.left, previewName))
      )
        return true;
    }
    return false;
  };
  const declaring = new Map<string, boolean>();
  for (const { from } of imports.values()) {
    if (!relativeModule(from) || declaring.has(from)) continue;
    declaring.set(from, declaresProductionId(resolve(tree), resolve(tree, from)));
  }
  // The production-only branches the decision opens.
  let gates = 0;
  each(fn, (node) => {
    if (
      (ts.isIfStatement(node) && undefinedTest(node.expression, previewName)) ||
      (ts.isConditionalExpression(node) && undefinedTest(node.condition, previewName)) ||
      (ts.isBinaryExpression(node) &&
        node.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandToken &&
        undefinedTest(node.left, previewName))
    )
      gates += 1;
  });
  let ungated: string | undefined;
  each(file, (node) => {
    if (ungated) return;
    if (ts.isStringLiteralLike(node) && productionOnlyIds.has(node.text) && !production(node))
      ungated = `it declares ${node.text} outside a production-only branch`;
    if (ts.isIdentifier(node) && references(node)) {
      const from = imports.get(node.text)?.from;
      if (from && declaring.get(from) === true && !production(node))
        ungated = `it uses ${node.text}, which declares a production-only id, outside a production-only branch`;
    }
  });
  if (ungated) return ungated;
  if (gates === 0) return "its preview decision gates nothing";
  return { stack, namer };
}
