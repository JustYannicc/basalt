import { createHash } from "node:crypto";
import { SafetyGateError, stableStringify } from "./contracts.ts";
import { frameworkDifferences, refuseFramework } from "./framework-refusal.ts";
import {
  parseFrameworkQualification,
  parseFrameworkProvenance,
  type FrameworkArtifactHashes,
  type FrameworkQualification,
  type FrameworkReleaseProvenance,
} from "./framework-qualification.ts";

export type FrameworkBuildReceipt = {
  schemaVersion: 1;
  produced: FrameworkReleaseProvenance;
  qualification: FrameworkQualification;
  releases: FrameworkReleaseProvenance[];
};

export const frameworkRegistryDigest = (value: unknown) =>
  createHash("sha256").update(stableStringify(value)).digest("hex");

/** Identical publication bytes can have another source revision after a source-only change. */
export function samePublication(
  left: FrameworkReleaseProvenance,
  right: FrameworkReleaseProvenance,
) {
  return (
    left.version === right.version &&
    left.sha256 === right.sha256 &&
    left.protocol === right.protocol &&
    left.browserSha256 === right.browserSha256 &&
    left.source.origin === right.source.origin &&
    left.source.sha256 === right.source.sha256
  );
}

const provenance = parseFrameworkProvenance;

function releaseKey(release: FrameworkReleaseProvenance) {
  return `${release.version}/${release.sha256}`;
}

export function qualifiedFrameworkRegistry(
  canonical: readonly FrameworkReleaseProvenance[],
  history: readonly FrameworkQualification[],
  produced: FrameworkReleaseProvenance,
  producerGitCommit: string,
  artifacts: FrameworkArtifactHashes,
): FrameworkBuildReceipt {
  const indexed = new Map<string, FrameworkReleaseProvenance>();
  for (const value of [
    ...canonical,
    ...history.map((entry) => parseFrameworkQualification(entry).provenance),
  ]) {
    const release = provenance(value);
    const previous = indexed.get(releaseKey(release));
    if (previous && stableStringify(previous) !== stableStringify(release))
      refuseFramework(
        "Conflicting qualified framework",
        frameworkDifferences(releaseKey(release), previous, release),
      );
    indexed.set(releaseKey(release), release);
  }
  const actual = provenance(produced);
  const previous = indexed.get(releaseKey(actual));
  if (previous && !samePublication(previous, actual))
    refuseFramework(
      "Produced framework conflicts with qualified",
      frameworkDifferences(releaseKey(actual), previous, actual),
    );
  // Reuse the original source binding for byte-identical publications instead of making their
  // immutable server identity ambiguous to retained builds.
  const current = previous ?? actual;
  indexed.set(releaseKey(current), current);
  const releases = [...indexed.values()].sort((left, right) =>
    releaseKey(left) < releaseKey(right) ? -1 : releaseKey(left) > releaseKey(right) ? 1 : 0,
  );
  return {
    schemaVersion: 1,
    produced: actual,
    qualification: parseFrameworkQualification({
      producerGitCommit,
      provenance: current,
      artifacts,
      registrySha256: frameworkRegistryDigest(releases),
    }),
    releases,
  };
}

export function renderQualifiedFrameworkRegistry(releases: readonly FrameworkReleaseProvenance[]) {
  const encodedHash = (value: string) =>
    JSON.stringify(Buffer.from(value, "hex").toString("base64"));
  let versionPrefix = releases[0]?.version ?? "";
  for (const release of releases) {
    while (!release.version.startsWith(versionPrefix)) versionPrefix = versionPrefix.slice(0, -1);
  }
  const entries = releases
    .map(
      (release) => `  [
    ${JSON.stringify(release.version.slice(versionPrefix.length))},
    ${encodedHash(release.sha256)},
    ${release.protocol},
    ${encodedHash(release.browserSha256)},
    ${JSON.stringify(release.source.revision)},
    ${encodedHash(release.source.sha256)},
  ],`,
    )
    .join("\n");
  return `// Generated by the host build from the canonical identities and its checked producer.
import type { FrameworkProvenance } from "../contracts/framework-provenance.ts";

// Compact storage keeps the cumulative history within the host's Worker budget.
const versionPrefix = ${JSON.stringify(versionPrefix)};
const releases: readonly (readonly [string, string, number, string, string, string])[] = [
${entries}
];

function hex(value: string) {
  return Array.from(atob(value), (byte) => byte.charCodeAt(0).toString(16).padStart(2, "0")).join(
    "",
  );
}

export const generatedFrameworkReleases: readonly FrameworkProvenance[] = releases.map(
  ([version, sha256, protocol, browserSha256, revision, packageSha256]) => ({
    version: versionPrefix + version,
    sha256: hex(sha256),
    protocol,
    browserSha256: hex(browserSha256),
    source: { origin: "basalt", revision, sha256: hex(packageSha256) },
  }),
);
`;
}

export function parseFrameworkBuildReceipt(value: unknown): FrameworkBuildReceipt {
  if (
    !value ||
    typeof value !== "object" ||
    !("schemaVersion" in value) ||
    value.schemaVersion !== 1 ||
    !("produced" in value) ||
    !("qualification" in value) ||
    !("releases" in value) ||
    !Array.isArray(value.releases)
  )
    refuseFramework(
      "Missing or malformed checked framework build receipt; rebuild the release candidate",
      [
        {
          resource: "framework-qualification.json",
          property: "receipt shape",
          expected: "schemaVersion 1 with produced, qualification and releases array",
          observed:
            value === null
              ? "null"
              : typeof value === "object"
                ? "missing or invalid required fields"
                : typeof value,
        },
      ],
    );
  const fields = (() => {
    try {
      return {
        produced: provenance(value.produced),
        qualification: parseFrameworkQualification(value.qualification),
        releases: value.releases.map(provenance),
      };
    } catch (error) {
      if (!(error instanceof SafetyGateError)) throw error;
      return refuseFramework("Malformed checked framework build receipt", [
        {
          resource: "framework-qualification.json",
          property: "receipt fields",
          expected: "valid producer, registry digest and framework provenance",
          observed: error.message,
        },
      ]);
    }
  })();
  const { qualification, releases } = fields;
  if (frameworkRegistryDigest(releases) !== qualification.registrySha256)
    refuseFramework("Checked framework registry digest changed; rebuild the release candidate", [
      {
        resource: "framework-qualification.json",
        property: "qualification.registrySha256",
        expected: qualification.registrySha256,
        observed: frameworkRegistryDigest(releases),
      },
    ]);
  return { schemaVersion: 1, produced: fields.produced, qualification, releases };
}
