import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

/**
 * The pool Worker's entry, and the one generated module both the Worker and the tools service
 * import its revision from, beside the other generated upstream inputs.
 */
export const poolWorkerEntry = "src/pool/worker.ts";
export const poolWorkerRevisionModule =
  ".upstream/apps/hosted/server/src/implementation/pool-worker-revision.ts";

const specifiers =
  /(?:import|export)\s[^"'`;]*?from\s*["'](\.{1,2}\/[^"']+)["']|import\s*\(\s*["'](\.{1,2}\/[^"']+)["']\s*\)|import\s*["'](\.{1,2}\/[^"']+)["']/g;

function resolveLocal(from: string, specifier: string): string | null {
  const base = resolve(dirname(from), specifier);
  for (const candidate of [base, `${base}.ts`, `${base}.tsx`, join(base, "index.ts")])
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  return null;
}

/**
 * Every local file the pool Worker imports, followed from its entry. Package imports are left
 * out: what the tools service relies on is the Worker's own routes and contracts.
 */
export function poolWorkerSources(root: string): string[] {
  const own = resolve(root, poolWorkerRevisionModule);
  const seen = new Set<string>();
  const pending = [resolve(root, poolWorkerEntry)];
  while (pending.length) {
    const file = pending.pop()!;
    if (seen.has(file) || file === own) continue;
    seen.add(file);
    if (!/\.tsx?$/.test(file)) continue;
    for (const match of readFileSync(file, "utf8").matchAll(specifiers)) {
      const next = resolveLocal(file, match[1] ?? match[2] ?? match[3]!);
      if (next) pending.push(next);
    }
  }
  return [...seen].map((file) => relative(root, file).split("\\").join("/")).sort();
}

/**
 * A hash of the pool Worker's local sources, path and bytes. Unchanged sources give the same
 * revision, so it adds no per-release input of its own. A generated source the Worker imports
 * still counts: today the production ops release does, so the revision moves with each release.
 */
export function poolWorkerRevision(root: string): string {
  const hash = createHash("sha256");
  for (const path of poolWorkerSources(root))
    hash
      .update(path)
      .update("\0")
      .update(readFileSync(join(root, path)))
      .update("\0");
  return hash.digest("hex");
}

/** Where the module sits inside the prepared tools runtime. */
export const poolWorkerRevisionPath =
  "apps/hosted/server/src/implementation/pool-worker-revision.ts";

/** The exact module preparation writes; the connector source check compares against it. */
export const poolWorkerRevisionSource = (root: string) =>
  `// Generated by Basalt's upstream preparation from the pool Worker's sources.\nexport const poolWorkerRevision = ${JSON.stringify(poolWorkerRevision(root))};\n`;

/** Run after every generated input the Worker imports, such as the production ops release. */
export function writePoolWorkerRevision(root: string, upstream: string): string {
  const target = join(upstream, poolWorkerRevisionPath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, poolWorkerRevisionSource(root));
  return poolWorkerRevision(root);
}
