import {
  mkdirSync,
  existsSync,
  readFileSync,
  symlinkSync,
  lstatSync,
  writeFileSync,
  appendFileSync,
} from "node:fs";
import { fileURLToPath } from "node:url";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { run } from "./process.ts";
import { readPatchManifest } from "./releases/patches.ts";
import { prepareUpstreamCheckout } from "./upstream-cache.ts";
import { installUpstreamDependencies } from "./upstream-dependencies.ts";
import { bundlePoolApp } from "./pool-app-bundle.ts";
import { writePoolWorkerRevision } from "./pool-worker-revision.ts";
import { prepareTestPlans } from "./ci/declarations.ts";
import { prepareE2e } from "./ci/prepare-e2e.ts";
import { checkRuntimeEnvironment } from "./ci/dependency-lifecycles.ts";

const root =
  process.argv[2] === "--root" && process.argv[3]
    ? resolve(process.argv[3])
    : fileURLToPath(new URL("../", import.meta.url));
const upstream = join(root, ".upstream");
const patchManifest = readPatchManifest(root);
const pin = JSON.parse(readFileSync(join(root, "upstream.json"), "utf8"));
if (!/^[a-f0-9]{40}$/.test(pin.commit)) throw new Error("Expected an immutable upstream commit");
await prepareUpstreamCheckout(
  upstream,
  pin,
  patchManifest.patches.map(({ file }) => join(root, "patches", file)),
);
prepareE2e(root, upstream);
prepareTestPlans(root, upstream);
bundlePoolApp(root, upstream);
// Installed catalog apps roll forward once per deployed Basalt revision.
const release = spawnSync("git", ["rev-parse", "HEAD"], {
  cwd: root,
  encoding: "utf8",
}).stdout?.trim();
if (!/^[a-f0-9]{40}$/.test(release ?? ""))
  throw new Error("Basalt must be prepared from a Git checkout");
writeFileSync(
  join(upstream, "apps/hosted/server/src/implementation/catalog-app-release.ts"),
  `// Generated by Basalt's upstream preparation.\nexport const catalogAppRelease = ${JSON.stringify(release)};\n`,
);
writeFileSync(
  join(upstream, "apps/hosted/cloud/src/implementation/production-ops-release.ts"),
  `// Generated by Basalt's upstream preparation.\nexport const productionOpsRelease = ${JSON.stringify(release)};\n`,
);
// The pool Worker imports the release above, so its revision is computed after it is written.
writePoolWorkerRevision(root, upstream);
await installUpstreamDependencies(upstream, pin.commit);
if (process.env.BASALT_CI_OMIT_RELEASE_DOWNLOADS === "true" && process.env.GITHUB_ENV) {
  for (const [key, value] of Object.entries(checkRuntimeEnvironment(upstream)))
    appendFileSync(process.env.GITHUB_ENV, `${key}=${value}\n`);
}
run("bun", ["install", "--frozen-lockfile", "--cwd", join(root, "src/setup")]);
run("bun", ["install", "--frozen-lockfile", "--cwd", join(root, "scripts/pool-tests/sdk")]);
run("bun", ["install", "--frozen-lockfile", "--cwd", join(root, "clients")]);
run("bun", ["install", "--frozen-lockfile", "--cwd", join(root, "src/tunnel")]);
run("bun", ["install", "--frozen-lockfile", "--cwd", join(root, "scripts/architecture")]);
run("bun", ["install", "--frozen-lockfile", "--cwd", join(root, "scripts/app-lint")]);
run("bun", ["install", "--frozen-lockfile", "--cwd", join(root, "scripts/startup-profiler")]);
const modules = join(root, "node_modules");
if (!existsSync(modules)) symlinkSync(".upstream/apps/hosted/cloud/node_modules", modules, "dir");
else if (!lstatSync(modules).isSymbolicLink())
  throw new Error("Basalt node_modules must link to the pinned cloud dependencies");
const revision = spawnSync("git", ["rev-parse", "HEAD"], { cwd: upstream, encoding: "utf8" });
if (revision.stdout.trim() !== pin.commit)
  throw new Error("Upstream checkout differs from the pin");
// Native stack discovery imports the authoring Worker's generated reference.
run("bun", ["run", "--cwd", "apps/hosted/cloud", "framework:build"], upstream);
mkdirSync(join(upstream, ".local"), { recursive: true });
writeFileSync(
  join(upstream, ".local/e2e-finalizer.json"),
  JSON.stringify({
    command: process.execPath,
    args: [join(root, "scripts/e2e-finalize.ts"), root],
  }),
);
// Deployment inventory includes static asset bytes before the full Worker build runs in CI.
run("node", ["scripts/setup-build.ts"], root);
