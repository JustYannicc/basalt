import { readFileSync } from "node:fs";
import { join } from "node:path";

/** Connect links the plugin release its manifest names, so a plugin bump needs no carry. */
export const obsidianPluginVersionPath = "apps/hosted/web/src/contracts/obsidian-plugin-version.ts";

export function obsidianPluginVersionSource(root: string) {
  const { version } = JSON.parse(
    readFileSync(join(root, "clients/obsidian/manifest.json"), "utf8"),
  );
  if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version))
    throw new Error("The Obsidian plugin manifest needs a release version");
  return `// Generated by Basalt's upstream preparation.\nexport const basaltSyncVersion = ${JSON.stringify(version)};\n`;
}
