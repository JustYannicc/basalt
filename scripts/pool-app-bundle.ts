import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { brand } from "../brand.ts";

export interface PoolAppFile {
  readonly path: string;
  readonly content: string;
}

export const poolFrameworkVersion = "0.0.1-beta.104-basalt.1";

const fontFiles = ["geist-sans.woff2", "geist-mono.woff2", "LICENSE.txt"];

/**
 * The dashboard's own Geist faces. The hosted compiler installs npm packages without their font
 * files, and binary public files would ride in the API Worker with the bundled source, so the
 * router serves the faces from its static assets and the pool page links them cross-origin.
 */
function poolFonts(): PoolAppFile {
  const face = (family: string, file: string) =>
    `@font-face {\n  font-family: "${family}";\n  src: url("https://${brand.host}/brand/fonts/${file}") format("woff2");\n  font-weight: 100 900;\n  font-style: normal;\n  font-display: swap;\n}\n`;
  return {
    path: "ui/public/fonts.css",
    content: `/* Generated by Basalt's pool app bundler: the dashboard's Geist faces, served by the router. */\n${face("Geist", "geist-sans.woff2")}${face("Geist Mono", "geist-mono.woff2")}`,
  };
}

/** Put the faces `fonts.css` links into the router's static assets. */
function placeRouterFonts(root: string, upstream: string) {
  const fonts = join(upstream, "packages/ui/src/implementation/styles/fonts");
  const served = join(root, "public/brand/fonts");
  mkdirSync(served, { recursive: true });
  for (const file of fontFiles) copyFileSync(join(fonts, file), join(served, file));
}

/** Bundle the app after patches choose the host's framework release. */
export function bundlePoolApp(root: string, upstream: string): readonly PoolAppFile[] {
  const source = join(root, "apps/pool");
  const framework: { version: string } = JSON.parse(
    readFileSync(join(upstream, "packages/apps/package.json"), "utf8"),
  );
  const files: PoolAppFile[] = [];
  const walk = (directory: string) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (["node_modules", "dist", "tests", "__tests__"].includes(entry.name)) continue;
      const path = join(directory, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile() && !/\.(test|spec)\.[^/]+$/.test(entry.name)) {
        const name = relative(source, path).split("\\").join("/");
        if (name === "ui/public/fonts.css") continue;
        let content = readFileSync(path, "utf8");
        if (name === "deployment.ts")
          content = `export const poolOrigin = ${JSON.stringify(`https://${brand.host}`)};\nexport const productName = ${JSON.stringify(brand.name)};\n`;
        if (name === "package.json") {
          const manifest = JSON.parse(content);
          manifest.dependencies = { ...manifest.dependencies, apps: framework.version };
          content = `${JSON.stringify(manifest, null, 2)}\n`;
        }
        files.push({ path: name, content });
      }
    }
  };
  walk(source);
  if (files.some((file) => file.path.startsWith("ui/"))) {
    files.push(poolFonts());
    placeRouterFonts(root, upstream);
  }
  files.sort((a, b) => a.path.localeCompare(b.path, "en"));
  if (files.length === 0) throw new Error("The pool app has no source files");
  const version = createHash("sha256").update(JSON.stringify(files)).digest("hex");
  const destination = join(upstream, "apps/hosted/server/src/implementation/pool-app-source.ts");
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(
    destination,
    `// Generated by Basalt's pool app bundler.\nimport type { SourceFiles } from "@executor-js/sdk/core";\nexport const poolAppVersion = ${JSON.stringify(version)};\nexport const poolAppFiles = ${JSON.stringify(files, null, 2)} satisfies SourceFiles;\n`,
  );
  // The provisioning signer and pool Worker's verifier always use the same implementation.
  copyFileSync(join(root, "src/pool/token.ts"), join(dirname(destination), "pool-token.ts"));
  return files;
}
